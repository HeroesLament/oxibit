//! Writes a tile type as a Rust source file in the literal form of [`crate::lit`].

use std::fmt::Write;

use crate::model::{Chip, Fuse, NONE, NO_DEFAULT};

fn bits(fuses: &[u32]) -> String {
    let v: Vec<String> = fuses
        .iter()
        .map(|&r| {
            let b = Fuse::from_raw(r);
            format!("{}({}, {})", if b.inverted() { "nf" } else { "f" }, b.frame(), b.bit())
        })
        .collect();
    format!("&[{}]", v.join(", "))
}

/// The source of tile type `ty`: a `pub static TILE: TileTypeLit`.
#[must_use]
pub fn tile_type_source(chip: &Chip, ty: usize) -> String {
    let t = &chip.tile_types[ty];
    let s = &chip.strings;
    let name = s.get(t.name);
    let mut o = String::new();
    // Writing to a String cannot fail.
    let _ = writeln!(o, "//! The `{name}` tile type, generated by oxibit-arch from Project Trellis tiledata.");
    let _ = writeln!(o, "//! Do not edit.\n");
    let _ = writeln!(o, "#![allow(unused_imports)]\n");
    let _ = writeln!(o, "use oxibit_arch::lit::{{f, nf, Arc, EnumLit, MuxLit, TileTypeLit, WordLit}};\n");
    let _ = writeln!(o, "pub static TILE: TileTypeLit = TileTypeLit {{");
    let _ = writeln!(o, "    name: {name:?},");
    let _ = writeln!(o, "    muxes: &[");
    for k in 0..t.muxes.keys.len() {
        let _ = writeln!(o, "        MuxLit {{");
        let _ = writeln!(o, "            sink: {:?},", s.get(t.muxes.keys[k]));
        let _ = writeln!(o, "            arcs: &[");
        for (src, fuses) in t.muxes.items(k) {
            let _ = writeln!(o, "                Arc {{ source: {:?}, bits: {} }},", s.get(src), bits(fuses));
        }
        let _ = writeln!(o, "            ],");
        let _ = writeln!(o, "        }},");
    }
    let _ = writeln!(o, "    ],");
    let _ = writeln!(o, "    enums: &[");
    for k in 0..t.enums.keys.len() {
        let default = match t.enum_def[k] {
            NO_DEFAULT => "None".to_owned(),
            d => format!("Some({:?})", s.get(d)),
        };
        let _ = writeln!(o, "        EnumLit {{");
        let _ = writeln!(o, "            name: {:?},", s.get(t.enums.keys[k]));
        let _ = writeln!(o, "            default: {default},");
        let _ = writeln!(o, "            options: &[");
        for (opt, fuses) in t.enums.items(k) {
            let _ = writeln!(o, "                ({:?}, {}),", s.get(opt), bits(fuses));
        }
        let _ = writeln!(o, "            ],");
        let _ = writeln!(o, "        }},");
    }
    let _ = writeln!(o, "    ],");
    let _ = writeln!(o, "    words: &[");
    for k in 0..t.words.keys.len() {
        let def = &t.word_def[t.word_def_start[k] as usize..t.word_def_start[k + 1] as usize];
        let def: Vec<&str> = def.iter().map(|&b| if b == 0 { "false" } else { "true" }).collect();
        let _ = writeln!(o, "        WordLit {{");
        let _ = writeln!(o, "            name: {:?},", s.get(t.words.keys[k]));
        let _ = writeln!(o, "            default: &[{}],", def.join(", "));
        let _ = writeln!(o, "            bits: &[");
        for (_, fuses) in t.words.items(k) {
            let _ = writeln!(o, "                {},", bits(fuses));
        }
        let _ = writeln!(o, "            ],");
        let _ = writeln!(o, "        }},");
    }
    let _ = writeln!(o, "    ],");
    let _ = writeln!(o, "    fixed: &[");
    for p in t.fixed.chunks_exact(2) {
        let _ = writeln!(o, "        ({:?}, {:?}),", s.get(p[0]), s.get(p[1]));
    }
    let _ = writeln!(o, "    ],");
    let _ = writeln!(o, "}};");
    o
}

/// The module (and file) name of a tile type or device: lower case, `-` as `_`.
#[must_use]
pub fn module_name(name: &str) -> String {
    name.to_lowercase().replace('-', "_")
}

fn opt(s: Option<&str>) -> String {
    s.map_or_else(|| "None".to_owned(), |s| format!("Some({s:?})"))
}

/// The source of device `dev`: a `pub static DEVICE: DeviceLit` that refers to
/// the tile types as `crate::tiles::<module>::TILE`.
#[must_use]
pub fn device_source(chip: &Chip, dev: usize) -> String {
    let d = &chip.devices[dev];
    let s = &chip.strings;
    let name = s.get(d.name);
    let mut o = String::new();
    let _ = writeln!(o, "//! The `{name}` device, generated by oxibit-arch from Project Trellis.");
    let _ = writeln!(o, "//! Do not edit.\n");
    let _ = writeln!(o, "use oxibit_arch::lit::{{");
    let _ = writeln!(o, "    DeviceLit, PackageLit, PinLit, PioMetaLit, QuadrantLit, SpineLit, TapLit, TileLit,");
    let _ = writeln!(o, "}};\n");
    let _ = writeln!(o, "pub static DEVICE: DeviceLit = DeviceLit {{");
    let _ = writeln!(o, "    name: {name:?},");
    let _ = writeln!(o, "    family: {:?},", s.get(d.family));
    let _ = writeln!(o, "    idcode: {:#010x},", d.idcode);
    let _ = writeln!(o, "    frames: {},", d.frames);
    let _ = writeln!(o, "    bits_per_frame: {},", d.bits_per_frame);
    let _ = writeln!(o, "    pad_bits_after_frame: {},", d.pad_bits_after_frame);
    let _ = writeln!(o, "    pad_bits_before_frame: {},", d.pad_bits_before_frame);
    let _ = writeln!(o, "    max_row: {},", d.max_row);
    let _ = writeln!(o, "    max_col: {},", d.max_col);
    let _ = writeln!(o, "    quadrants: &[");
    for q in &d.quadrants {
        let n = s.get(q.name);
        let _ = writeln!(o, "        QuadrantLit {{ name: {n:?}, x0: {}, y0: {}, x1: {}, y1: {} }},", q.x0, q.y0, q.x1, q.y1);
    }
    let _ = writeln!(o, "    ],");
    let _ = writeln!(o, "    taps: &[");
    for t in &d.taps {
        let n = s.get(t.name);
        let _ = writeln!(o, "        TapLit {{ name: {n:?}, lx0: {}, lx1: {}, rx0: {}, rx1: {} }},", t.lx0, t.lx1, t.rx0, t.rx1);
    }
    let _ = writeln!(o, "    ],");
    let _ = writeln!(o, "    spines: &[");
    for p in &d.spines {
        let _ = writeln!(o, "        SpineLit {{ name: {:?}, x: {}, y: {} }},", s.get(p.name), p.x, p.y);
    }
    let _ = writeln!(o, "    ],");
    let _ = writeln!(o, "    packages: &[");
    for p in &d.packages {
        let _ = writeln!(o, "        PackageLit {{");
        let _ = writeln!(o, "            name: {:?},", s.get(p.name));
        let _ = writeln!(o, "            pins: &[");
        for x in &p.pins {
            let _ = writeln!(
                o,
                "                PinLit {{ name: {:?}, col: {}, row: {}, pio: {:?} }},",
                s.get(x.name),
                x.col,
                x.row,
                s.get(x.pio)
            );
        }
        let _ = writeln!(o, "            ],");
        let _ = writeln!(o, "        }},");
    }
    let _ = writeln!(o, "    ],");
    let _ = writeln!(o, "    pio_meta: &[");
    for m in &d.pio_meta {
        let dqs = opt((m.dqs != NONE).then(|| s.get(m.dqs)));
        let function = opt((m.function != NONE).then(|| s.get(m.function)));
        let _ = writeln!(
            o,
            "        PioMetaLit {{ bank: {}, col: {}, row: {}, pio: {:?}, dqs: {dqs}, function: {function} }},",
            m.bank,
            m.col,
            m.row,
            s.get(m.pio)
        );
    }
    let _ = writeln!(o, "    ],");
    let _ = writeln!(o, "    tiles: &[");
    for t in &d.tiles {
        let ty = module_name(s.get(chip.tile_types[t.ty as usize].name));
        let _ = writeln!(
            o,
            "        TileLit {{ name: {:?}, ty: &crate::tiles::{ty}::TILE, start_frame: {}, start_bit: {}, frames: {}, bits: {} }},",
            s.get(t.name),
            t.start_frame,
            t.start_bit,
            t.frames,
            t.bits
        );
    }
    let _ = writeln!(o, "    ],");
    let _ = writeln!(o, "}};");
    o
}

/// `tiles/mod.rs`: one module per tile type and the sorted `ALL` table.
#[must_use]
pub fn tiles_mod_source(chip: &Chip) -> String {
    let s = &chip.strings;
    let mut o = String::from("//! Every tile type, generated by oxibit-arch from Project Trellis tiledata.\n//! Do not edit.\n\n");
    for t in &chip.tile_types {
        let _ = writeln!(o, "pub mod {};", module_name(s.get(t.name)));
    }
    let _ = writeln!(o, "\nuse oxibit_arch::lit::TileTypeLit;\n");
    let _ = writeln!(o, "/// Every tile type, sorted by name.");
    let _ = writeln!(o, "pub static ALL: &[&TileTypeLit] = &[");
    for t in &chip.tile_types {
        let _ = writeln!(o, "    &{}::TILE,", module_name(s.get(t.name)));
    }
    let _ = writeln!(o, "];");
    o
}

/// `devices/mod.rs`: one module per device and the `ALL` table.
#[must_use]
pub fn devices_mod_source(chip: &Chip) -> String {
    let s = &chip.strings;
    let mut o = String::from("//! Every device, generated by oxibit-arch from Project Trellis.\n//! Do not edit.\n\n");
    for d in &chip.devices {
        let _ = writeln!(o, "pub mod {};", module_name(s.get(d.name)));
    }
    let _ = writeln!(o, "\nuse oxibit_arch::lit::DeviceLit;\n");
    let _ = writeln!(o, "pub static ALL: &[&DeviceLit] = &[");
    for d in &chip.devices {
        let _ = writeln!(o, "    &{}::DEVICE,", module_name(s.get(d.name)));
    }
    let _ = writeln!(o, "];");
    o
}
